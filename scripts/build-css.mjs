// Builds app/globals.css from styles/globals.src.css using Tailwind's pure-JS compiler.
// Why: on some Windows machines an Application Control policy blocks Tailwind's native
// scanner (@tailwindcss/oxide), so the Next.js Tailwind loader cannot run. This needs no
// native code. Candidates are collected with a broad token regex; Tailwind ignores
// tokens that are not utilities.
//
//   node scripts/build-css.mjs          one-shot build (npm run css, prebuild)
//   import { buildCss } from "./build-css.mjs"   used by scripts/dev.mjs for watch mode
import { compile } from "tailwindcss";
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

export const SOURCE_CSS = path.join(root, "styles/globals.src.css");
export const OUTPUT_CSS = path.join(root, "app/globals.css");
export const SCAN_DIRS = ["app", "components", "lib"].map((d) => path.join(root, d));
const SCAN_EXT = /\.(tsx?|jsx?|mdx?)$/;
const HEADER = "/* GENERATED by scripts/build-css.mjs from styles/globals.src.css. Do not edit. */\n";

function walk(dir, out = []) {
  if (!existsSync(dir)) return out;
  for (const n of readdirSync(dir)) {
    const p = path.join(dir, n);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (SCAN_EXT.test(n)) out.push(p);
  }
  return out;
}

/** True when a changed path can affect the generated CSS. */
export function isRelevant(file) {
  const abs = path.resolve(file);
  if (abs === OUTPUT_CSS) return false; // never react to our own output
  if (abs === SOURCE_CSS) return true;
  return SCAN_DIRS.some((d) => abs.startsWith(d + path.sep)) && SCAN_EXT.test(abs);
}

/** Compiles and writes the CSS. Skips the write when output is identical. */
export async function buildCss() {
  const candidates = new Set();
  for (const dir of SCAN_DIRS) {
    for (const f of walk(dir)) {
      for (const t of readFileSync(f, "utf8").split(/[\s"'`<>={}()]+/)) if (t) candidates.add(t);
    }
  }
  const compiler = await compile(readFileSync(SOURCE_CSS, "utf8"), {
    base: root,
    loadStylesheet: async (id, base) => {
      const file = id === "tailwindcss" ? require.resolve("tailwindcss/index.css") : path.resolve(base, id);
      return { path: file, base: path.dirname(file), content: readFileSync(file, "utf8") };
    },
  });
  const css = HEADER + compiler.build([...candidates]);
  const previous = existsSync(OUTPUT_CSS) ? readFileSync(OUTPUT_CSS, "utf8") : null;
  if (previous === css) return { changed: false, bytes: css.length, tokens: candidates.size };
  writeFileSync(OUTPUT_CSS, css);
  return { changed: true, bytes: css.length, tokens: candidates.size };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const r = await buildCss();
  console.log(`globals.css: ${r.changed ? "written" : "unchanged"}, ${r.bytes} bytes, ${r.tokens} candidate tokens`);
}
